"""Стоимость юнита. Научного результата не определяет вовсе.

Этот файл вправе меняться свободно: от него зависит, в какое задание
попадёт замороженный юнит, и ничего больше. `task_id` от веса не зависит
(это отдельный гейт), поэтому перераскладка не меняет ни одного числа в
артефактах.

Модель снята с 156 фактических юнитов ступени 4000 прогона 35805206374.
Прежняя была снята с ОДНОЙ дымовой пробы и ошибалась дважды подряд.
"""

from __future__ import annotations

#: Прогон, давший замеры. Калибровка без происхождения — фольклор.
MEASURED_ON = "run 35805206374, look 4000, ubuntu-latest, 2026-09-23"

#: Шесть подгонок `сек = a + b * эффективная_ставка` на ступени 4000, по
#: одной на шард. Каждая внутри себя даёт R2 = 0.983..0.996; общая по
#: пулу — всего 0.881, потому что пул смешивает раннеры разной скорости.
#:
#: Почему аффинная, а не пропорциональная: у каждого периода есть работа,
#: не зависящая от числа событий (сдвинуть часы, обновить окно, тронуть
#: аккумулятор). По событиям масштабируется только их собственный цикл.
#: Фиксированное слагаемое даёт 31-43% стоимости при ставке 1.
RUNNER_FITS = (
    (2.90, 9.3736),    # шард 0
    (31.92, 16.5375),  # шард 1
    (5.53, 9.2637),    # шард 2
    (15.50, 18.1319),  # шард 3
    (10.01, 13.1534),  # шард 4
    (2.74, 18.1873),   # шард 5
)

#: Ступень, на которой сняты коэффициенты
FITTED_AT_LOOK = 4000

#: Размах шести наблюдений: наклоны от 9.26 до 18.19. Это МАКСИМУМ
#: ШЕСТИ ЗАМЕРОВ, а не верхняя граница распределения скоростей раннеров,
#: и гейтом он НЕ является. Сравнивать запас с выборочным размахом
#: значило бы делать вид, что шесть наблюдений исчерпали совокупность.
#: Число оставлено как наблюдение, которое объясняет, откуда берётся
#: консервативность огибающей.
OBSERVED_RUNNER_SPREAD = 18.1873 / 9.2637

#: Потолок задания GitHub для этого воркфлоу: timeout-minutes 350
PLATFORM_CAP_HOURS = 350.0 / 60.0

#: Операционный бюджет шарда. Прежние 4.0 пробиты фактом 4.188 на первой
#: же производственной ступени, и пробиты не случайно: прежняя модель
#: занижала ХУДШИЙ шард на 17.2%, завышая при этом ИТОГ на 9.9%. Так
#: ведёт себя модель, считающая раннеры одинаковыми.
#:
#: Экономить задания здесь незачем: репозиторий публичный, раннеры
#: стандартные, платные минуты не расходуются, а потолок матрицы 256 при
#: прежнем максимуме 95. Поэтому целимся ниже, а не впритык.
SHARD_BUDGET_HOURS = 2.5

#: Требование к бюджету формулируется в два шага, и ни один из них не
#: выдаёт выборку за границу распределения:
#:
#:   1. веса строятся от КОНСЕРВАТИВНОЙ модели — верхней огибающей по
#:      наблюдённым раннерам (`seconds_for`);
#:   2. худшее предсказанное задание обязано укладываться в
#:      операционную цель, а сама цель — лежать СУЩЕСТВЕННО ниже
#:      платформенного потолка.
#:
#: «Существенно» — объявленный операционный выбор, а не статистика.
#: Репозиторий публичный, стандартные раннеры не тарифицируются, потолок
#: матрицы 256 при нынешних десятках заданий. Экономить пять заданий
#: ценой приближения к таймауту бессмысленно: бесплатный грузовик всё
#: равно едет по одному мосту.
MIN_BUDGET_HEADROOM = 2.0

BUDGET_HEADROOM = PLATFORM_CAP_HOURS / SHARD_BUDGET_HOURS

#: Линейность по `look` НЕ ИЗМЕРЕНА: все 156 юнитов посчитаны на одной
#: ступени. Пересчёт на 16000 и 64000 — экстраполяция, и её покрывает
#: только запас выше.
LOOK_LINEARITY_IS_ASSUMED_NOT_MEASURED = True


#: Накладные расходы ОДНОГО задания: подготовка, checkout'ы, установка
#: Python, скачивание манифеста, выгрузка артефакта, завершение.
#:
#: Измерено по отметкам, а не предположено: прогон 35805206374 шард 0 дал
#: 2 с до счёта и 2 с после; прогон 35839807992 шард 3 — 5 с до счёта
#: (три checkout'а вместо двух плюс скачивание манифеста). Здесь стоит
#: заведомо большее число: очередь до старта, сеть и выгрузка крупного
#: артефакта в замер не попали.
#:
#: Без этого слагаемого планировщик всегда выбирает МАКСИМАЛЬНУЮ дробность:
#: при фиксированном числе слотов makespan монотонно падает с числом
#: заданий, и ничто не платит за само задание.
JOB_OVERHEAD_SECONDS = 30.0

#: Сколько заданий матрицы S5b вправе идти ОДНОВРЕМЕННО.
#:
#: Это `jobs.<id>.strategy.max-parallel`, и он ограничивает одновременность
#: ВНУТРИ матрицы: «will run a maximum of two jobs at a time, even if there
#: are runners available to run all six jobs at once» (docs GitHub, matrix
#: strategies).
#:
#: Зачем он здесь. Предел одновременных заданий даётся НА ПЛАН, а не на
#: репозиторий: Free 20, Pro 40. 23 сентября 41 задание ступени 16000
#: заняли все 20 слотов аккаунта, и пилот M8 в соседнем репозитории простоял
#: в очереди, не начавшись. S5b живёт в общей вычислительной квартире.
#:
#: Прежняя формулировка «рычагов ровно три: доработать, отменить, поднять
#: лимит» была НЕВЕРНА — max-parallel существует и документирован. Ошибка
#: увела рассуждение к упаковке 41 задания в 40 вместо очевидного: не
#: занимать весь общий ресурс.
#:
#: 6 — сознательный выбор политики, а не измеренная константа. Цель не
#: «утилизировать пул», а сделать S5b фоновой нагрузкой, которая больше
#: никогда не кладёт соседние репозитории: из наблюдённых 20 слотов шесть
#: забирают 30%, четырнадцать остаются остальным. Число не подбиралось
#: бенчмарком и подбираться не должно. Если пул окажется пустым, ручку
#: можно поднять — это решение о вежливости, а не о науке.
MAX_PARALLEL = 6

#: Предел параллелизма — ИСПОЛНИТЕЛЬНЫЙ параметр. В `task_id` он не входит
#: и научный результат не определяет: меняется только то, в каком порядке
#: исполняются те же самые замороженные юниты.
MAX_PARALLEL_IS_EXECUTION_ONLY = True


def seconds_for(rate: float, look: int) -> float:
    """Верхняя огибающая по шести НАБЛЮДЁННЫМ раннерам.

    Не среднее и не медиана. В потолок задания упирается худший шард, а
    его определяет самый медленный вытянутый раннер, а не типичный. Брать
    середину значило бы планировать под раннер, которого может не быть.

    Огибающая считается поточечно, потому что `a` и `b` у подгонок
    разменяны между собой: на низких ставках медленнее один шард, на
    высоких другой.
    """
    at_fit = max(a + b * max(rate, 0.0) for a, b in RUNNER_FITS)
    return at_fit * (look / FITTED_AT_LOOK)


class SplitEconomyUnmeasured(Exception):
    """Деление ключей потребовалось, а его экономия не измерена."""


#: Сколько стоимости юнита НЕ делится между группами ключей (генерация
#: потоков общая). Прежняя модель ставила сюда 0.05 и делила остальное
#: нацело. Это допущение не проверено ни разу: на 4000 и 16000
#: `groups_needed == 1` у всех рук, то есть ось ключей не включалась.
#:
#: Единственное касание — дымовая проба, гонявшая 1 группу из 2. Её факт
#: ближе к «половина ключей стоит как все», чем к модельным 0.525, но
#: развести это с классом раннера одной точкой нельзя: там менялись
#: одновременно ступень, доля ключей и раннер.
#:
#: Поэтому здесь НЕ ЧИСЛО, а `None`. Планировщик, которому понадобилось
#: деление, обязан отказать и потребовать замер, а не подставить
#: правдоподобную константу.
UNDIVIDED_SHARE: float | None = None


def groups_needed(rate: float, look: int, keys_total: int) -> int:
    """Сколько групп ключей нужно руке, чтобы влезть в бюджет.

    На 4000 и 16000 возвращает единицу у всех рук сетки: полный юнит
    укладывается в бюджет, делить нечего. Впервые деление понадобится на
    64000 — и там же впервые заработает `s5b_shard.merge`.

    Если полный юнит в бюджет НЕ лезет, а экономия деления не измерена,
    это отказ. Подставить сюда правдоподобную долю означало бы построить
    план на непроверенной экономии — ровно та ошибка, которой стоила
    прежняя модель, только дороже: на 64000 юниты идут часами.
    """
    full = seconds_for(rate, look)
    budget = SHARD_BUDGET_HOURS * 3600.0
    if full <= budget:
        return 1
    if UNDIVIDED_SHARE is None:
        raise SplitEconomyUnmeasured(
            f"ставка {rate:g} на ступени {look}: полный юнит {full/3600:.2f} ч "
            f"против бюджета {SHARD_BUDGET_HOURS} ч, а экономия деления "
            f"ключей НЕ ИЗМЕРЕНА (UNDIVIDED_SHARE is None)")
    for groups in range(1, keys_total + 1):
        if full * (UNDIVIDED_SHARE
                   + (1.0 - UNDIVIDED_SHARE) / groups) <= budget:
            return groups
    return keys_total


def fits_platform(seconds: float) -> bool:
    return seconds <= PLATFORM_CAP_HOURS * 3600.0
