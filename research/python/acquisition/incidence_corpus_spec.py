def by_fit(fit: Fit) -> tuple[Candidate, ...]:
    return tuple(c for c in CANDIDATES if c.fit is fit)


def serious_candidates_checked() -> int:
    """Кандидаты, дошедшие до реальной проверки, а не отсеянные по названию."""
    return len(CANDIDATES)


def stop_rule_fired() -> bool:
    """True — поиск Q1a закрыт. Функция, а не память о том, что мы решили."""
    return serious_candidates_checked() >= STOP_AFTER_SERIOUS_CANDIDATES


def rediscovered() -> tuple[Candidate, ...]:
    """Кандидаты, которые проект уже оценивал и забыл, что оценивал."""
    return tuple(c for c in CANDIDATES if c.rediscovered)
