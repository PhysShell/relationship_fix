class Resolution(Enum):
    """Фактическое разрешение меток ОДНОГО чата."""

    MILLISECONDS = "MILLISECONDS"
    SECONDS = "SECONDS"
    MINUTES = "MINUTES"
    #: сообщений слишком мало, чтобы отличить минуты от везения
    UNDETERMINED = "UNDETERMINED"


#: Сколько сообщений нужно, чтобы вывод «MINUTES» был выводом, а не совпадением.
#:
#: Направления доказательства НЕ СИММЕТРИЧНЫ, и это надо сказать вслух:
#:
#:   SECONDS доказывается ОДНОЙ меткой с ненулевыми секундами — контрпример;
#:   MINUTES доказывается только отсутствием таких меток, а отсутствие при
#:   n сообщениях случайно возникает с вероятностью ~(1/60)^n.
#:
#: При n = 5 это 1.3e-9. Порог поставлен там; всё, что ниже, честно уходит в
#: UNDETERMINED, а не подклеивается к большинству.
MINUTES_VERDICT_MIN_MESSAGES = 5


def classify_resolution(dates: list[int], *,
                        min_messages: int = MINUTES_VERDICT_MIN_MESSAGES) -> Resolution:
    """Метки в миллисекундах эпохи -> разрешение чата. Чистая функция."""
    if any(d % 1000 for d in dates):
        return Resolution.MILLISECONDS
    if any(d % 60_000 for d in dates):
        return Resolution.SECONDS
    if len(dates) < min_messages:
        return Resolution.UNDETERMINED
    return Resolution.MINUTES


