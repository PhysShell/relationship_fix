# --------------------------------------------------------------------------
# 3. Идентичность: вложенные режимы, primary — самый строгий выживший
# --------------------------------------------------------------------------

#: `alterconf` дискретна (.3 .4 .5 .6 .7 .95) и является ПОРЯДКОВОЙ шкалой,
#: хотя выглядит как вероятность. Порог выбираем мы, явно и заранее.
#:
#: Документация подтверждает дословно: «While values are presented as
#: probabilities between 0 and 1, they are really ordinal and are codes
#: indicative of how certain we are». И далее: «Egoids ... have the highest
#: value possible we assign, .95. Alterids with confidence values of .6 or
#: greater are good (~80% of the records)».
#:
#: То, что авторы называют .6 хорошим, — их суждение, а не наш порог. Ступени
#: объявлены до счёта именно поэтому.
IDENTITY_REGIMES: tuple[tuple[str, float], ...] = (
    ("I0", 0.95),
    ("I1", 0.70),
    ("I2", 0.60),
)

#: Primary — самый строгий режим, который не уничтожает корпус. Порог «не
#: уничтожает» объявляется здесь, ДО того как станет виден размер выборки.
IDENTITY_MINIMUM_DYADS = 200

#: Порог считается ПОСЛЕ всех остальных сужений, а не до них. Иначе легко
#: объявить «I0 выжил на 230 диадах», а после coverage-гейта обнаружить 87.
IDENTITY_THRESHOLD_APPLIED_AFTER = ("channel_filter", "dedup_policy",
                                    "coverage_restriction")

#: Следствие для формулировки estimand, и его нельзя забыть при выводах.
#: Правило отбора по уверенности — это ОПРЕДЕЛЕНИЕ ПОПУЛЯЦИИ, зависящее от
#: данных, пусть и объявленное заранее. Поэтому писать надо
#: «среди диад, удовлетворяющих предзарегистрированному правилу допуска по
#: уверенности идентификации», а НЕ «диады NetHealth» вообще.
IDENTITY_POPULATION_PHRASE = (
    "among dyads satisfying the preregistered identity-confidence admission rule"
)


def primary_identity_regime(surviving_dyads: dict[str, int]) -> str | None:
    """Строжайший режим, оставляющий хотя бы `IDENTITY_MINIMUM_DYADS` пар."""
    for name, _ in IDENTITY_REGIMES:
        if surviving_dyads.get(name, 0) >= IDENTITY_MINIMUM_DYADS:
            return name
    return None


