class DuplicateProbe(Enum):
    """Три пробы значат РАЗНОЕ, и смешивать их нельзя.

    Главное следствие: D1 сам по себе дедупликатором не становится. «Совместимо
    с двойным логированием» и «является двойным логированием» — разные
    утверждения, и второе требует D0 либо D2.
    """

    #: доказательство точного двойного логирования
    D0_EXACT_MIRROR = "D0_exact_mirror"
    #: свидетельство, СОВМЕСТИМОЕ с двойным логированием
    D1_NEAR_MIRROR = "D1_near_mirror"
    #: распределительная поддержка того, что D1 — не просто плотный трафик
    D2_DISTRIBUTIONAL_SUPPORT = "D2_distributional_support"


#: Окно D1, зафиксированное ДО просмотра распределения.
#:
#: Обоснование, а не вкус — и ПОПРАВЛЕННОЕ. Прежняя редакция говорила, что
#: несколько секунд набегают «от округления», и это неверно: секундное
#: квантование само по себе разводит две записи одного события максимум примерно
#: на секунду. Правильная декомпозиция:
#:
#:     5 с = квантование класса «1 секунда»
#:         + допуск на расхождение часов и момента журналирования двух аппаратов
#:
#: Второе слагаемое и есть основное. Окно остаётся консервативной пробой,
#: объявленной заранее; меняется причина, а не число.
DEDUP_NEAR_WINDOW_SECONDS = 5.0


#: Ширина полосы задержки для фона D2. Полосы равной ширины и не пересекаются:
#: [0,5), [5,10), [10,15), ...
D2_BAND_SECONDS = 5.0


@dataclass(frozen=True, slots=True)
class DuplicateEvidence:
    """Что нашли по каждой пробе. Числа — снаружи, толкование — здесь.

    ФОН БЕРЁТСЯ ИЗ ТЕХ ЖЕ ПОТОКОВ на ненулевых задержках, а не из пуассоновской
    фантазии. Прежняя редакция считала ожидание как
    `len(sx) * len(sy) * 2W / span`, то есть предполагала постоянную
    интенсивность. Человеческие сообщения идут пачками, поэтому такой нуль
    занижает случайные совпадения и раздувает превышение. Полосы задержки
    сохраняют и плотность, и пачечность, потому что это те же самые данные.
    """

    pairs_examined: int
    d0_exact: int
    #: счётчики по полосам: [0,5), [5,10), [10,15), ...
    band_counts: tuple[int, ...]

    @property
    def d1_near(self) -> int:
        return self.band_counts[0] if self.band_counts else 0

    @property
    def background(self) -> float:
        """Средний счёт по ненулевым полосам."""
        rest = self.band_counts[1:]
        return sum(rest) / len(rest) if rest else 0.0

    @property
    def d2_ratio(self) -> float | None:
        bg = self.background
        return self.d1_near / bg if bg > 0 else None


class DuplicateVerdict(Enum):
    #: дубли доказаны: их надо сводить, иначе плотность завышена
    PRESENT = "duplicates_present"
    #: сигнатуры не наблюдается — но это НЕ «двойное логирование невозможно»
    NO_SIGNATURE_OBSERVED = "no_signature_observed"
    #: данных не хватило, чтобы вопрос вообще был задан
    INSUFFICIENT = "insufficient"


def classify_duplicates(
    evidence: DuplicateEvidence,
    *,
    minimum_pairs: int = 1000,
    excess_ratio: float = 3.0,
) -> DuplicateVerdict:
    """Чистая функция. Отсутствие D0 ничего не доказывает — за тем и D1/D2.

    D1 в одиночку вердикта не даёт НИКОГДА: плотный трафик сам по себе набивает
    нулевую полосу. Нужен либо D0, либо превышение нулевой полосы над соседними.

    Формулировка чистого исхода узкая намеренно: `NO_SIGNATURE_OBSERVED`
    означает, что следов не увидели, а не что двойное логирование невозможно.
    """
    if evidence.pairs_examined < minimum_pairs:
        return DuplicateVerdict.INSUFFICIENT
    if evidence.d0_exact > 0:
        return DuplicateVerdict.PRESENT
    ratio = evidence.d2_ratio
    if ratio is not None and ratio >= excess_ratio:
        return DuplicateVerdict.PRESENT
    return DuplicateVerdict.NO_SIGNATURE_OBSERVED


#: ИТОГ ПРОБЫ (полный файл, 60 486 564 строки, 587 участников, 5 595 пар,
#: у которых есть обе перспективы):
#:
#:     D0  точных зеркал (та же миллисекунда)      = 1 362 951
#:     D1  нулевая полоса |dt| в [0,5) с           = 1 913 647
#:
#:     фон по полосам задержки, те же потоки:
#:       [ 5,10) с   400 794      [20,25) с   212 472
#:       [10,15) с   296 217      [25,30) с   199 697
#:       [15,20) с   242 020      [30,35) с   190 656
#:                                [35,40) с   178 792
#:
#:     D2  нулевая полоса / среднее фона           = 7.8x
#:     D2  нулевая полоса / СОСЕДНЯЯ полоса        = 4.8x   (консервативнее)
#:
#: ПОПРАВКА К ПЕРВОЙ РЕДАКЦИИ. Сначала фон считался как
#: `len(sx) * len(sy) * 2W / span`, то есть по постоянной интенсивности, и дал
#: «превышение в 308 раз». Это была пуассоновская фантазия: человеческие
#: сообщения идут пачками, такой нуль занижает случайные совпадения и раздувает
#: превышение примерно в сорок раз. Честное число — 7.8x, а против соседней
#: полосы 4.8x. Сам спад фона (400 794 -> 178 792) и есть та пачечность,
#: которой постоянная интенсивность не видит вовсе.
#:
#: Вывод при этом не изменился и держится на D0: полтора миллиона зеркал на ТОЙ
#: ЖЕ МИЛЛИСЕКУНДЕ случайностью не объясняются ни при каком фоне. У 90.7%
#: совпадений нулевой полосы ещё и одинаковый `eventtypedetail`.
#:
#: Документация проекта подтверждает дословно: «it is possible for an event to
#: involve two NetHealth participants and therefore there can be two records for
#: the same event because that event was logged on two different devices».
#:
#: Смещение РАЗНОСТНОЕ: удвоены только пары участник-участник, потому что у
#: внешнего собеседника учётного телефона нет. Подделан был бы не масштаб, а
#: зависимость плотности от типа собеседника.

# --------------------------------------------------------------------------
# 2a. ПОЧИНКА — отдельно от обнаружения и ПОКА НЕ В СИЛЕ
# --------------------------------------------------------------------------
#
# Обнаружение и починка разделены намеренно. Если алгоритм ремонта начнёт
# влиять на доказательство существования проблемы, доказательства больше нет.
# Поэтому: сначала вердикт, потом политика.
#
# И у починки есть свой неприятный случай, который жадное сопоставление решает
# неверно:
#
#     A шлёт msg1
#     A шлёт msg2 через секунду
#     оба телефона пишут оба
#     → четыре строки в одном окне
#
# «Нашёл ближайшую пару → удалил» способно сцепить msg1 с копией msg2.
# Поэтому правильная починка — не жадная:
#
#     та же неупорядоченная диада
#     + то же ФИЗИЧЕСКОЕ направление
#     + совместимый подтип события
#     + |dt| <= окно
#     → сопоставление ОДИН-К-ОДНОМУ по минимальному расстоянию
#
# с отдельным счётчиком неоднозначных кластеров, а не с молчаливым выбором.
#
# Времени для сопоставления мало. У двух записей одного события есть и другие
# поля, и сперва надо ИЗМЕРИТЬ, какие из них согласованы, а не предположить:
#
#     eventtypedetail, messagetype, length, bytes
#
# Если `length`/`bytes` совпадают почти всегда, они снимают ровно тот риск,
# из-за которого жадность опасна: в пятисекундной куче из четырёх строк
# msg1 и msg2 различаются длиной, даже когда неразличимы временем.
#: `messagetype` ВЫЧЕРКНУТ: в документации iOS-базы сказано прямо — «Ignore
#: is_delievered and message_service field», и про message_service там же:
#: «not have any documentation about this, probably internal indicator».
#: Сопоставлять по полю, которое авторы велят игнорировать, — плохая идея.
#:
#: `length` наоборот ПОДТВЕРЖДЁН: серверный первичный ключ проекта для
#: iOS-SMS — (phone_number, time_stamp, destination, text_length, is_from_me).
#: То есть длина уже использовалась ими как различающее поле.
DEDUP_MATCH_FIELDS_CANDIDATE = ("eventtypedetail", "length", "bytes")

#: ПОЧЕМУ серверная дедупликация НЕ сняла найденные зеркала. Её первичный ключ
#: включает `phone_number` — номер того аппарата, с которого снята запись. У
#: двух участников номера разные, поэтому две копии одного события ключом не
#: совпадают и обе переживают дедупликацию ПО ПОСТРОЕНИЮ. Проект чистил
#: дубликаты ВНУТРИ устройства; межустройственные зеркала — другой класс.
SERVER_DEDUP_KEY_IS_PER_DEVICE = True

#: Какую копию оставлять — и ЧТО ДЕЛАТЬ С НЕПАРНЫМИ. Прежняя редакция говорила
