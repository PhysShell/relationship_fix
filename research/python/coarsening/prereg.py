"""PREREG q1c_coarsening_operator — объявлено ДО первого прогона.

ЧТО ЭТО ЗА ЗАДАЧА НА САМОМ ДЕЛЕ
-------------------------------
Мы не изобретаем «специальную статистику для переписок». Задача уже
разложена наукой, и стоит назвать её именами, потому что имена приносят
готовые ошибки, на которых можно не повторяться:

  temporal networks / time aggregation — Ribeiro, Perra & Baronchelli
  показали, что довольно небольшое temporal aggregation существенно меняет
  свойства процесса поверх сети, и отдельно варьировали НАЧАЛО окна, чтобы
  эффект не оказался свойством конкретной сетки. Отсюда §5 (phase);

  coarse data — Heitjan & Rubin: вместо истинного значения наблюдается
  МНОЖЕСТВО значений, которое могло его породить. `10:31` означает
  `[10:31:00, 10:32:00)`. Отсюда весь дизайн: не «оценить ошибку из
  теории», а применить настоящий оператор к настоящим событиям;

  measurement error с validation sample — наши секундные чаты играют роль
  парной точной меры при грубой. Но см. §1: они НЕ истина;

  partial orders / uncertain event logs в process mining — там давно не
  выдумывают total order для событий с одинаковой меткой, а хранят частичный
  порядок и исследуют множество допустимых линейных продолжений. Это
  математическая версия нашего `TiePolicy.BOUNDED`. Отсюда §7.

ЦЕЛЬ: измерить, какую информацию и какое смещение создаёт огрубление часов
1 с -> 60 с для метрик, зависящих от ПОРЯДКА событий.

НЕ ЦЕЛЬ: оценить абсолютную incidence (Q1a закрыт, `Q1A_STATUS =
DOCUMENTED_LIMITATION`); откалибровать генератор числом; сказать что-либо о
романтических парах; предсказать поведение Telegram.
"""

from __future__ import annotations

import math
from dataclasses import dataclass

# ---------------------------------------------------------------------------
# §1. Опорный поток. НЕ истина.
# ---------------------------------------------------------------------------

#: Родное разрешение целевого подмножества: 520 диадических чатов Share and
#: Multiply, 9 549 453 сообщения.
REFERENCE_RESOLUTION_SECONDS = 1.0

#: Называть это ground truth НЕЛЬЗЯ, и не из вежливости. Внутри одной секунды
#: порядок всё равно неизвестен, поэтому опорная мера сама несёт
#: неоднозначность — в эпидемиологии для такого есть термин alloyed gold
#: standard. Мы меряем ДОБАВОЧНУЮ потерю при 1 с -> 60 с, а не потерю
#: относительно совершенной меры. Baseline ambiguity на 1 с ИЗМЕРЯЕТСЯ и
#: входит в отчёт, а не принимается за ноль.
REFERENCE_IS_NOT_GROUND_TRUTH = True
REFERENCE_TERM = "reference resolution"

#: Целевое разрешение: ровно то, что выдаёт минутный экспорт WhatsApp —
#: 72.70% этого же корпуса.
OBSERVED_RESOLUTION_SECONDS = 60.0


# ---------------------------------------------------------------------------
# §2. Оператор. Детерминированный, без единого сгенерированного события.
# ---------------------------------------------------------------------------

def coarsen(timestamp: float, delta: float = OBSERVED_RESOLUTION_SECONDS,
            phase: float = 0.0) -> float:
    """C_{Δ,φ}(t) = φ + Δ·floor((t − φ)/Δ).

    Ровно это и делает минутный источник: пол по настенной минуте. Никакой
    генерации событий, никакого Poisson, никакого jitter, никакой подогнанной
    интенсивности. Те же самые байты событий, другой знаменатель часов.
    """
    return phase + delta * math.floor((timestamp - phase) / delta)


