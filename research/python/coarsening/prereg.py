# ---------------------------------------------------------------------------

#: НАБЛЮДАТЕЛЬ A: видит только метки. Сортирует по (метка, произвольный
#: tie-break) и внутри корзины порядка НЕ ЗНАЕТ. Это тот наблюдатель, ради
#: которого существует `TiePolicy.STRICT`.
#:
#: НАБЛЮДАТЕЛЬ B: видит метки И порядок строк в файле. Настоящий минутный
#: экспорт WhatsApp — транскрипт, и строки в нём идут в истинном порядке.
#: Для B стоимость огрубления топологически НУЛЕВАЯ по построению.
#:
#: Мы меряем A. Это не потому, что B не существует, а потому, что проект уже
#: отказался считать файловый порядок хронологией: в ledger'е acquisition
#: `ordering.equal_second_cross_actor_chronology` стоит UNAVAILABLE, и в
#: Telegram Desktop отказ от id-порядка стоил ровно того же. Мерить A —
#: значит мерить ЦЕНУ ЭТОГО ОТКАЗА, а она и есть наш вопрос.
#:
#: Сказать это вслух обязательно: иначе результат «огрубление дорого» легко
#: прочесть как свойство минутных данных, тогда как это свойство минутных
#: данных ПЛЮС нашего решения не верить порядку строк.
