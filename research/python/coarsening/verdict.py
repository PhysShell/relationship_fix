"""Правила агрегации прогона по 520 диадам — ОБЪЯВЛЕНЫ ДО ПРОСМОТРА РАСПРЕДЕЛЕНИЙ.

Три примера уже показали, что оценка STRICT может лежать вне допустимого
множества. Превращать три иллюстрации в утверждение о корпусе можно только
если правила счёта названы заранее: иначе «насколько часто» и «насколько
далеко» определятся ровно тем, что получилось.

ТЕРМИНОЛОГИЯ, и она здесь не украшение
--------------------------------------
Слой порядка считается ТОЧНО, слой времени — валидной внешней оболочкой.
Поэтому про две величины говорится по-разному:

    N      sharp identified set — точное множество значений, совместимых с
           наблюдёнными минутными метками;

    RMTR   valid outer identification envelope — заведомо не уже истинного
           множества.

Из этого следует усиление, а не ослабление вывода:

    STRICT ∉ outer envelope
        ⟹ STRICT ∉ неизвестного sharp set, лежащего ВНУТРИ оболочки.

То есть «не совпал с каким-то возможным порядком» — слабая формулировка.
Верная: оценка лежит снаружи заведомо слишком широкой оболочки.

ЧТО ЭТИМ ДОКАЗЫВАЕТСЯ
---------------------
Раньше цепочка была эмпирической: ambiguity -> исключение -> исключённые
быстрее -> RMTR уезжает вверх. Теперь она структурная:

    грубое наблюдение
      -> множество допустимых latent histories
      -> каждая даёт значение целевого функционала
      -> BOUNDED охватывает все такие значения
    STRICT ∉ этого множества

Значит STRICT здесь НЕ является шумной или неэффективной оценкой ТОЙ ЖЕ
величины. Он считает ДРУГОЙ функционал:

    цель    метрика по всем возможностям под какой-нибудь хронологией,
            совместимой с наблюдением;
    STRICT  метрика по возможностям, ПЕРЕЖИВШИМ правило исключения,
            которое само зависит от неоднозначности.

И выживание зависит от поведения: быстрое плотное взаимодействие даёт больше
межакторных столкновений, значит больше исключений. Для будущего эксперимента
это остаётся механизмом пост-тритмент отбора.
"""

