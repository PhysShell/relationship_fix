# ---------------------------------------------------------------------------
# 1-2. Как часто STRICT снаружи и насколько далеко
# ---------------------------------------------------------------------------

#: Нарушение меньше секунды не считается нарушением. `11.0001` против
#: `11.0000` формально снаружи, практически — нет, и булев подсчёт без этого
#: пола измерял бы точность арифметики, а не науку.
VIOLATION_FLOOR_SECONDS = 1.0


@dataclass(frozen=True, slots=True)
class Violation:
    """Насколько точка вне интервала. Ноль — внутри."""

    absolute_seconds: float
    #: нарушение, отнесённое к ширине оболочки: «на сколько ширин промахнулись»
    relative_to_width: float
    above: bool

    @property
    def outside(self) -> bool:
        return self.absolute_seconds > VIOLATION_FLOOR_SECONDS


def violation(point: float, low: float, high: float) -> Violation:
    if point > high:
        gap, above = point - high, True
    elif point < low:
        gap, above = low - point, False
    else:
        return Violation(0.0, 0.0, False)
    width = max(high - low, 1e-9)
    return Violation(gap, gap / width, above)


# ---------------------------------------------------------------------------
# 3. Насколько информативен BOUNDED
# ---------------------------------------------------------------------------

def relative_width(low: float, high: float) -> float:
    """Для N: ширина, отнесённая к середине."""
    middle = (low + high) / 2.0
    return (high - low) / middle if middle else float("inf")


def multiplicative_width(low: float, high: float) -> float:
    """Для положительного RMTR удобнее отношение концов, а не разность."""
    return high / low if low > 0 else float("inf")


# ---------------------------------------------------------------------------
# 4. Кто раздувает интервал: порядок или время внутри корзины
# ---------------------------------------------------------------------------

#: ТРИГГЕР, объявленный заранее. Писать второй DP ради резких временных
#: границ имеет смысл ТОЛЬКО если порядок отвечает меньше чем за половину
#: ширины. Иначе получится прекрасный solver, оплаченный теоретической
#: возможностью его написать: сужать надо то, что широко, а не то, что
#: интересно сужать.
SHARPEN_TIME_IF_ORDER_SHARE_BELOW = 0.5

#: И вторая половина того же правила: если даже широкая оболочка уже
#: принимает решение, дальнейшее сужение не изменит ничего.
SHARPEN_ONLY_WHERE_DECISION_IS_OPEN = True


def order_share(order_width: float, full_width: float) -> float:
    """Доля ширины, создаваемая неопределённостью ПОРЯДКА."""
    return order_width / full_width if full_width > 0 else 1.0


