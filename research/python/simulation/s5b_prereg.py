def latent_simulations() -> int:
    """Сколько РАЗНЫХ латентных потоков нужно этапу 1."""
    scaled = len(EFFECT_REGIMES) - len(MAGNITUDE_NOT_APPLICABLE_TO)
    regimes = len(MAGNITUDE_NOT_APPLICABLE_TO) + scaled * len(EFFECT_MAGNITUDE_MULTIPLIERS)
    return len(OPPORTUNITY_RATE_GRID) * regimes * len(C_REACTIVITY_POINTS)


def measurement_cells() -> int:
    """Сколько оценок гейта измерения даёт этап 1, включая бесплатные оси."""
    return (latent_simulations() * len(ACQUISITION_RESOLUTIONS_SECONDS)
            * len(HORIZONS_SECONDS) * len(DELTA_FRACTIONS_OF_HORIZON))


