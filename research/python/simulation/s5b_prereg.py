class Admissibility(Enum):
    USABLE = "usable"
    BORDERLINE = "borderline / structurally ambiguous"
    UNUSABLE = "unusable for this endpoint"


#: BORDERLINE перестаёт быть словом и становится ПРАВИЛОМ.
#:
#: Оценка популяционного интервала конечна, поэтому у гейта нужен допуск. Он
#: же задаёт третью категорию: ячейка BORDERLINE, если хоть один конец
#: интервала лежит к +-delta ближе, чем на GATE_MARGIN_FRACTION * delta.
GATE_MARGIN_FRACTION = 0.10


def admissibility(low: float, high: float, delta: float) -> Admissibility:
    """metrics -> Admissibility. Чистая функция, объявлена ДО поверхности.

    Гейт измерения пройден, когда интервал НЕ пересекает +-delta: либо целиком
    снаружи, либо целиком внутри. Близость любого конца к границе меньше
    допуска делает ячейку BORDERLINE независимо от формального исхода.
    """
    margin = GATE_MARGIN_FRACTION * delta
    closest = min(abs(low - delta), abs(low + delta),
                  abs(high - delta), abs(high + delta))
    if closest < margin:
        return Admissibility.BORDERLINE
    outside = low > delta or high < -delta
    inside = -delta <= low and high <= delta
    return Admissibility.USABLE if (outside or inside) else Admissibility.UNUSABLE


