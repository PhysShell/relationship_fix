#: Раньше семантика `N_eligible` на правой границе была DEFERRED. Она
#: появилась здесь сама: `OBSERVATION_DAYS` — фиксированные окна, а ось
#: разрешений делает контрпример частью исследования:
#:
#:     t = 119, H = 60, окно до 120:  N(1 с) = 0, N(60 с) = 1
#:
#: ПОПРАВКА ВТОРОГО ЧТЕНИЯ, и она существенная. Прошлая редакция обещала
#: «ОДНО И ТО ЖЕ множество возможностей во всех руках оси разрешений».
#: Такого множества НЕ СУЩЕСТВУЕТ. Огрубление затем и введено, что
#: возможности при разных Δ сливаются и возникают иначе; нельзя взять
#: возможность №17 при 60 с и потребовать её существования при 1 с. Прежняя
#: формулировка требовала соответствия между объектами, которого нет.
ELIGIBILITY_IS_A_TIME_REGION_NOT_AN_OPPORTUNITY_SET = True

#: ПРАВИЛЬНАЯ КОНСТРУКЦИЯ — ОБЩАЯ ОБЛАСТЬ ИНИЦИАЦИИ. Она задаётся на оси
#: ВРЕМЕНИ, один раз, при опорном (самом грубом) разрешении; возможность
#: любого разрешения допустима тогда и только тогда, когда её время попадает
#: в опорную корзину из этой области. Топология рук может различаться —
#: область риска у них общая.
ELIGIBILITY_REFERENCE_RESOLUTION_SECONDS = 60.0
ELIGIBILITY_PHASE_SECONDS = 0.0
ELIGIBILITY_GUARD_BINS = 1

#: И ФОРМУЛА ИСПРАВЛЕНА. Прежняя пара строк противоречила себе: условие
#:
#:     ref_start + H <= window_end
#:
#: при H = 60 и окне 120 объявляло опорную корзину [60,120) допустимой,
#: то есть признавало тот самый t = 119, ради которого всё затевалось, —
#: а рядом стояла константа `GUARD_BINS = 1`, которая в формуле не
#: участвовала. Смысл запаса — «у КАЖДОГО события этой корзины есть полный
#: горизонт», значит в окно должен попадать КОНЕЦ корзины:
ELIGIBILITY_RULE = ("a reference bin b is in the initiation region iff "
                    "b.start + ELIGIBILITY_GUARD_BINS * Δ_ref + H <= window_end; "
                    "an opening at ANY resolution is eligible iff its time "
                    "falls in a reference bin from that region")

#: ПРЕДУСЛОВИЕ ВЛОЖЕННОСТИ, без которого «родительская корзина» — пустые
#: слова: все Δ оси делят Δ_ref и делят фазу. Для (1, 5, 15, 60) при фазе 0
#: это выполнено, и проверяется тестом, а не взглядом.
RESOLUTIONS_MUST_NEST_IN_THE_REFERENCE_BIN = True

#: И СВЯЗЬ С §4.0, которую легко не заметить: область инициации — ПРЕФИКС по
#: времени, поэтому она сохраняет монотонность eligibility, на которой стоит
#: теорема N_min = 0 => N_max = 0. Не сохраняла бы — растяжка сработала бы.
INITIATION_REGION_IS_A_TIME_PREFIX = True


def initiation_region_end(window_end: float, horizon: float, *,
                          reference_delta: float = ELIGIBILITY_REFERENCE_RESOLUTION_SECONDS,
                          guard_bins: int = ELIGIBILITY_GUARD_BINS) -> float:
    """Последнее допустимое НАЧАЛО опорной корзины. Чистая функция."""
    return window_end - horizon - guard_bins * reference_delta


def is_eligible(t: float, *, window_end: float, horizon: float,
                reference_delta: float = ELIGIBILITY_REFERENCE_RESOLUTION_SECONDS,
                phase: float = ELIGIBILITY_PHASE_SECONDS,
                guard_bins: int = ELIGIBILITY_GUARD_BINS) -> bool:
    """Допустима ли возможность в момент `t` — ОДИНАКОВО ПРИ ЛЮБОМ Δ.

    Момент относится к своей опорной корзине, и решает она. Поэтому событие
    t = 119 при H = 60 и окне 120 недопустимо и при 1 с, и при 60 с: оба раза
    его родительская корзина — [60, 120), а её конец из окна уже выпал.
    """
    parent = phase + reference_delta * math.floor((t - phase) / reference_delta)
    return parent + guard_bins * reference_delta + horizon <= window_end

