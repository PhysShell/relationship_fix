#: ПРЕЖНЯЯ РЕДАКЦИЯ брала person-period-weighted RMTR: mean_i(B_i / N_i).
#: Претензия рецензента формулировалась как «при N = 0 множество слагаемых
#: само зависит от латентной хронологии, значит [mean L_i, mean U_i] не
#: резкая граница». В ТАКОЙ форме претензия не проходит, и это проверено:
#:
#:     N_min = 0  =>  N_max = 0
#:
#: Аргумент. Eligibility монотонна по времени: `start + H <= window_end`, и
#: допустимые корзины образуют ПРЕФИКС. Ожидающее возвращение создаётся
#: только ОТКРЫТИЕМ. Значит в первую корзину, содержащую сообщение партнёра,
#: любой порядок входит с пустым состоянием, и первое же сообщение партнёра
#: в ней открывает возможность. Если эта корзина допустима — N >= 1 при
#: ЛЮБОМ порядке; если нет, то и все последующие недопустимы, и N = 0 при
#: любом. Середины не существует.
#:
#: Проверено исчерпывающим перебором: 57 840 конфигураций, из них 14 412 с
#: N_min = 0, случаев N_min = 0 < N_max — НИ ОДНОГО. Множество слагаемых
#: наблюдаемо, знаменатель фиксирован, среднее концов на этом не ломается.
N_ZERO_IS_ORDER_INVARIANT = True
N_ZERO_INVARIANCE_RESTS_ON = ("eligibility is monotone in time (a prefix)",
                              "a pending return is created only by a counted opening")
#: Но это ТЕОРЕМА С ПРЕДУСЛОВИЯМИ, а не свойство природы. Если S6 введёт
#: немонотонную eligibility, она рухнет молча. Поэтому в `bounded` заведён
#: статус `Definedness.AMBIGUOUS`, недостижимый СЕГОДНЯ, и тест-растяжка,
#: которая обязана упасть в тот день, когда он станет достижим.
