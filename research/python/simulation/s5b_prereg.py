class Admissibility(Enum):
    USABLE = "usable"
    BORDERLINE = "borderline / structurally ambiguous"
    UNUSABLE = "unusable for this endpoint"


#: BORDERLINE перестаёт быть словом и становится ПРАВИЛОМ: ячейка
#: пограничная, если хоть один конец интервала лежит к ±δ ближе, чем на
#: GATE_MARGIN_FRACTION * delta. Допуск нужен потому, что популяционные
#: границы мы ИНТЕГРИРУЕМ численно, а не знаем точно.
GATE_MARGIN_FRACTION = 0.10


def distance_to_gate(low: float, high: float, delta: float) -> float:
    """Насколько ближний конец интервала близок к ближней границе решения.

    ЧТО ЭТО НЕ ТАКОЕ: не «на сколько надо сдвинуть интервал, чтобы вердикт
    перевернулся». Это близость к границе, и выбрана она потому, что ровно
    ЕЁ использует допуск BORDERLINE. Одна величина на два применения лучше,
    чем две почти одинаковые: именно близость конца к ±δ делает вердикт
    ячейки хрупким к ошибке численного интегрирования.
    """
    return min(abs(low - delta), abs(low + delta),
               abs(high - delta), abs(high + delta))


def base_admissibility(low: float, high: float, delta: float) -> Admissibility:
    """Гейт БЕЗ допуска: только USABLE / UNUSABLE. Чистая функция."""
    outside = low > delta or high < -delta
    inside = -delta <= low and high <= delta
    return Admissibility.USABLE if (outside or inside) else Admissibility.UNUSABLE


def admissibility(low: float, high: float, delta: float) -> Admissibility:
    """Гейт С допуском: три состояния. Объявлено ДО поверхности."""
    if distance_to_gate(low, high, delta) < GATE_MARGIN_FRACTION * delta:
        return Admissibility.BORDERLINE
    return base_admissibility(low, high, delta)


#: ДЕТЕРМИНИРОВАННЫЙ ВЫБОР ДВУХ BORDERLINE. Иначе «две пограничные ячейки»
#: при сорока семи пограничных — это researcher degree of freedom после
#: просмотра поверхности.
BORDERLINE_SELECTION = ("две ячейки: ближайшая к гейту ИЗНУТРИ (base USABLE) "
                        "и ближайшая СНАРУЖИ (base UNUSABLE); ничьи "
                        "разрешаются лексикографически по кортежу осей")
BORDERLINE_TIE_BREAK = ("rate", "resolution", "horizon", "delta_fraction",
                        "regime", "magnitude", "c_point", "days")


@dataclass(frozen=True, slots=True)
class Cell:
    """Ячейка поверхности: координаты по осям и популяционные границы."""

    axes: tuple            #: в порядке BORDERLINE_TIE_BREAK
    low: float
    high: float
    delta: float


def select_borderline_cells(cells) -> tuple[Cell | None, Cell | None]:
    """(ближайшая изнутри, ближайшая снаружи). Исполняемое правило.

    ПОЧЕМУ ФУНКЦИЯ, А НЕ АБЗАЦ. Прошлая редакция описала правило прозой,
    и runner всё равно должен был бы решать сам, что такое «ближайшая
    изнутри» ПОСЛЕ того, как `admissibility` уже схлопнула обе стороны в
    BORDERLINE. Десять строк кода дешевле археологии через неделю.
    """
    def pick(want: Admissibility) -> Cell | None:
        pool = [c for c in cells
                if base_admissibility(c.low, c.high, c.delta) is want]
        if not pool:
            return None
        return min(pool, key=lambda c: (distance_to_gate(c.low, c.high, c.delta),
                                        c.axes))

    return pick(Admissibility.USABLE), pick(Admissibility.UNUSABLE)


