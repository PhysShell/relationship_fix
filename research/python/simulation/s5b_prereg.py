#: подозрительно подходящая: N = 0, экстремумы, ties, частичная
#: идентификация.
#:
#: ПОЭТОМУ КОНЕЦ ОПРЕДЕЛЯЕТСЯ ОБОБЩЁННО-ОБРАТНОЙ, а не «корнем»:
#:
