#: возрастают, поэтому корень единственный». ЭТО НЕВЕРНО. Из монотонности
#: следует только существование точки смены знака. Возможно ПЛАТО
#:
#:     g > 0 при λ < a,   g = 0 на [a, b],   g < 0 при λ > b
#:
