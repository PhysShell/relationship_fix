#: ПОЧЕМУ ГРАНИЦЫ РУКИ — НЕ СРЕДНЕЕ КОНЦОВ И НЕ ΣB_lo/ΣN_hi.
#:
#: Среднее концов отвечало на другой вопрос (person-period-weighted). А
#: наивная оболочка ΣB_lo/ΣN_hi .. ΣB_hi/ΣN_lo — это ловушка `B_min/N_max`,
#: поднятая этажом выше: концы достигаются на РАЗНЫХ допустимых порядках.
#: Проверено: на 298 случайных руках она разошлась с полным перебором в 156.
#: Больше половины — то есть «иногда совпадает» здесь означает «совпадает
#: примерно как монетка».
#:
#: Правильно — Динкельбах по всей руке. Везение структурное: периоды
#: независимы, целевая функция аддитивна, поэтому
#:
#:     min по совместным порядкам Σ(B_i − λN_i) = Σ min(B_i − λN_i)
#:
