class Gate(Enum):
    """Два РАЗНЫХ гейта. Сваливать их в один INCONCLUSIVE запрещено."""

    #: ширина идентификации под BOUNDED относительно ±δ
    MEASUREMENT = "measurement"
    #: доверительный интервал относительно ±δ
    SAMPLING = "sampling"


class Verdict(Enum):
    """Комбинированный исход. Четыре состояния, и третье с четвёртым — не
    одно и то же: одно лечится участниками, другое не лечится ничем."""

    #: измерение идентифицирует, выборка решает
    IDENTIFIED_AND_DECISIVE = "IDENTIFIED_AND_DECISIVE"
    #: измерение идентифицирует, выборки не хватает -> БОЛЬШЕ N ПОМОЖЕТ
    SAMPLING_INCONCLUSIVE = "SAMPLING_INCONCLUSIVE"
    #: интервал идентификации сам пересекает границу решения
    #: -> БОЛЬШЕ N НЕ ПОМОЖЕТ
    MEASUREMENT_AMBIGUOUS = "MEASUREMENT_AMBIGUOUS"
    #: и то и другое
    BOTH_AMBIGUOUS = "BOTH_AMBIGUOUS"


def verdict(measurement_identified: bool, sampling_decisive: bool) -> Verdict:
    """Чистая функция. Разделение куплено слишком дорого, чтобы потерять его
    в дизайне мощности."""
    if measurement_identified and sampling_decisive:
        return Verdict.IDENTIFIED_AND_DECISIVE
    if measurement_identified:
        return Verdict.SAMPLING_INCONCLUSIVE
    if sampling_decisive:
        return Verdict.MEASUREMENT_AMBIGUOUS
    return Verdict.BOTH_AMBIGUOUS


